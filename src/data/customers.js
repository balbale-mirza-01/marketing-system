const pad = (n, l) => String(n).padStart(l, "0");

function makeAccounts(i, list, isBiz, prospect) {
  if (prospect) return [];
  return Array.from({ length: 2 + (i % 3) }, (_, k) => {
    const [name, kind] = list[(i + k * 2) % list.length];
    return {
      id: `a${i}-${k}-${isBiz ? "b" : "p"}`,
      name,
      kind,
      number: `${pad(100 + i, 4)}-${pad((i * 7919 + k * 131) % 10000000, 7)}-${k + 1}`,
      balance: (isBiz ? 850 : 120) * 1e6 * ((((i + 3) * (k + 2)) % 9) + 1),
      status: (i + k) % 7 === 0 ? "blocked" : "active",
      openedAt: daysFrom(-(60 + ((i * 37 + k * 90) % 900))),
    };
  });
}

function makeActivity(i, accs, by, key) {
  return {
    interactions: Array.from({ length: 3 + (i % 3) }, (_, k) => ({
      id: `i-${key}-${k}`,
      ...INTERACTIONS[(i + k * 3) % 7],
      by,
      date: daysFrom(-(k * 9 + (i % 5) + 1)),
      accountId: accs.length ? accs[k % accs.length].id : null,
    })),
    followups: Array.from({ length: 2 + (i % 2) }, (_, k) => ({
      id: `f-${key}-${k}`,
      ...FOLLOWUPS[(i + k) % 4],
      by,
      date: daysFrom(-(k * 12 + 3)),
    })),
    extras: Array.from({ length: 3 }, (_, k) => ({
      id: `x-${key}-${k}`,
      ...EXTRAS[(i + k) % 4],
      by,
      date: daysFrom(-(k * 15 + 5)),
    })),
    nextAction: NEXT[i % 5],
  };
}

