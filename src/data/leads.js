const FU = [
  "تماس اولیه و معرفی محصول انجام شد",
  "ارسال فهرست مدارک و فرم درخواست",
  "پیگیری تلفنی؛ مشتری زمان بیشتری خواست",
  "جلسه حضوری در شعبه برگزار شد",
];
const CHANNELS = ["تلفن", "حضوری", "پیامک"];

export const leadsSeed = ROWS.map((r, i) => {
  const [
    name,
    phone,
    sources,
    status,
    ownerId,
    ago,
    next,
    interest,
    customerId,
    type,
    lostReason,
  ] = r;
  const steps =
    status === "lost"
      ? ["new", "assigned", "contacted", "lost"]
      : FLOW.slice(0, FLOW.indexOf(status) + 1);
  const gap = Math.max(1, Math.floor(ago / steps.length));
  return {
    id: `l${i + 1}`,
    name,
    phone,
    sources,
    status,
    ownerId,
    interest,
    customerId,
    type,
    createdAt: daysFrom(-ago, 9),
    nextFollowUp: ["converted", "lost"].includes(status)
      ? null
      : daysFrom(next),
    lostReason: lostReason || "",
    notes:
      FLOW.indexOf(status) >= 3
        ? "درآمد ماهانه مشخص و گردش حساب مناسب؛ واجد شرایط دریافت محصول."
        : "",
    history: steps.map((s, k) => ({
      status: s,
      date: daysFrom(-ago + k * gap, 9 + k),
      by: k === 0 ? null : ownerId,
    })),
    followups: Array.from(
      { length: Math.max(0, steps.length - 2) },
      (_, k) => ({
        id: `lf${i}-${k}`,
        note: FU[(i + k) % 4],
        channel: CHANNELS[k % 3],
        by: ownerId,
        date: daysFrom(-ago + (k + 1) * gap, 11),
      }),
    ),
  };
});
